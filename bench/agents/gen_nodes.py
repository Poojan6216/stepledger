"""Write bench/agents/_nodes_generated.py: enrich_cve_0 .. enrich_cve_79 as module-level functions.

The LangGraph plugin identifies each task by module.qualname and rejects closures, and its task
cache keys on that identity plus the input, so every node needs its own real function
(build spec, Appendix B).

    uv run python -m bench.agents.gen_nodes
"""

from __future__ import annotations

from pathlib import Path

COUNT = 80
HEADER = '''"""Generated by bench/agents/gen_nodes.py. Do not edit."""

from __future__ import annotations

from typing import Any

from langgraph.runtime import Runtime

from bench.agents.investigator import AgentContext, InvestigationState, step
'''

TEMPLATE = """

async def enrich_cve_{i}(
    state: InvestigationState, runtime: Runtime[AgentContext]
) -> dict[str, Any]:
    return await step("enrich_cve_{i}", state, runtime)
"""


def main() -> None:
    body = HEADER + "".join(TEMPLATE.format(i=i) for i in range(COUNT))
    body += (
        "\n\nENRICH_NODES = [\n" + "".join(f"    enrich_cve_{i},\n" for i in range(COUNT)) + "]\n"
    )
    out = Path(__file__).with_name("_nodes_generated.py")
    out.write_text(body)
    print(f"wrote {out} ({COUNT} nodes)")


if __name__ == "__main__":
    main()
